import { readFileSync, writeFileSync } from "node:fs";
const p = "client/client.js";
let s = readFileSync(p, "utf8");
const start = s.indexOf("        // Words only become a facet");
const end = s.indexOf("        }, [plugins, skills]);", start);
if (start < 0 || end < 0) throw new Error("block not found");
const after = end + "        }, [plugins, skills]);\n".length;
s = s.slice(0, start) + s.slice(after);
writeFileSync(p, s, "utf8");
