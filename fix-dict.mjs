const p = "client/client.js";
let s = readFileSync(p, "utf8");
const zh = "                lensAll: '全部',\n";
const en = "                lensAll: 'All',\n";
if (!s.includes(zh) || !s.includes(en)) throw new Error("anchors missing");
s = s.replace(zh, zh + "                lensMcp: 'MCP',\n                facetOrigin: '来源',\n                facetShape: '形态',\n                facetWord: '词',\n                facetSkill: '技能',\n                facetUi: '有界面',\n                facetHost: '纯后端',\n                rowsFiled: '已把 {n} 项加入「{name}」',\n");
s = s.replace(en, en + "                lensMcp: 'MCP',\n                facetOrigin: 'Origin',\n                facetShape: 'Shape',\n                facetWord: 'Word',\n                facetSkill: 'Skill',\n                facetUi: 'Has UI',\n                facetHost: 'Headless',\n                rowsFiled: 'Filed {n} into \"{name}\"',\n");
writeFileSync(p, s, "utf8");
